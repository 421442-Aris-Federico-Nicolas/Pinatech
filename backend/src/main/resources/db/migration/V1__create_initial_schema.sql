CREATE INDEX idx_technical_service_tickets_status ON technical_service_tickets(status);
CREATE INDEX idx_technical_service_tickets_created_at ON technical_service_tickets(created_at DESC);
CREATE INDEX idx_ticket_status_history_ticket_id ON ticket_status_history(ticket_id);
