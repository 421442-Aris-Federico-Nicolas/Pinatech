LOCK TABLE products, inventory, order_items, inventory_movements IN SHARE ROW EXCLUSIVE MODE;

CREATE TABLE product_variants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
    color_name VARCHAR(100) NOT NULL,
    color_hex VARCHAR(7),
    display_order INTEGER NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_product_variants_color_name CHECK (BTRIM(color_name) <> ''),
    CONSTRAINT chk_product_variants_color_hex CHECK (color_hex IS NULL OR color_hex ~ '^#[0-9A-Fa-f]{6}$'),
    CONSTRAINT chk_product_variants_display_order CHECK (display_order >= 0)
);

CREATE INDEX idx_product_variants_product ON product_variants(product_id, display_order, id);
CREATE UNIQUE INDEX uq_product_variants_product_color ON product_variants(product_id, LOWER(color_name)) WHERE is_active;

INSERT INTO product_variants(product_id, color_name, display_order)
SELECT id, 'Unico', 0 FROM products;

INSERT INTO inventory(product_id, available_quantity, reserved_quantity, updated_at)
SELECT product.id, 0, 0, CURRENT_TIMESTAMP
FROM products product
WHERE NOT EXISTS (SELECT 1 FROM inventory WHERE inventory.product_id = product.id);

