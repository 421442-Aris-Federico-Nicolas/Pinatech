UPDATE order_items SET variant_id = variant.id, variant_color_name = variant.color_name, variant_color_hex = variant.color_hex FROM product_variants variant WHERE variant.product_id = order_items.product_id;
UPDATE inventory_movements SET variant_id = variant.id FROM product_variants variant WHERE variant.product_id = inventory_movements.product_id;

